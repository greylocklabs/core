/**
 * Writes core's themes as Kotlin, so every app draws with the colors, corners, type and motion the desktop apps
 * read from the same files. Each key becomes the field of the same name in camel case. A theme takes what it
 * leaves out from callie.toml, which sets every key, as the desktop's theme loader does.
 */
abstract class GenerateThemes : DefaultTask() {
  @get:InputDirectory
  abstract val themes: DirectoryProperty

  @get:OutputDirectory
  abstract val outputDir: DirectoryProperty

  @TaskAction
  fun generate() {
    val base = read(themes.get().file("callie.toml").asFile)
    val files = themes.get().asFile.listFiles { f -> f.name.endsWith(".toml") }!!.sortedBy { it.nameWithoutExtension }
    val themes = files.joinToString("\n") { file ->
      val id = file.nameWithoutExtension
      val own = read(file)
      val value = { section: String, key: String -> own[section]?.get(key) ?: base.getValue(section).getValue(key) }
      val fields = { section: String, convert: (String, String) -> String ->
        base.getValue(section).keys.joinToString("") { key -> "      ${camel(key)} = ${convert(key, value(section, key))},\n" }
      }
      """
      |  /** core's themes/${file.name}. */
      |  val ${camel(id)} = ThemeTokens(
      |    id = "$id",
      |    name = ${value("theme", "name")},
      |    dark = ${value("theme", "variant") == "\"dark\""},
      |    colors = GreylockColors(
      |${fields("colors") { _, v -> "Color(0xFF${v.trim('"').removePrefix("#").uppercase()})" }}    ),
      |    shape = GreylockShape(
      |${fields("shape") { _, v -> "$v.dp" }}    ),
      |    type = GreylockType(
      |${fields("type") { _, v -> v }}    ),
      |    motion = GreylockMotion(
      |${fields("motion") { k, v -> if (k == "bounce") "${v}f" else v }}    ),
      |  )
      |
      """.trimMargin()
    }
    val all = files.joinToString(", ") { camel(it.nameWithoutExtension) }
    val out = outputDir.get().file("org/greylocklabs/ui/Themes.kt").asFile
    out.parentFile.mkdirs()
    out.writeText(
      "// Generated by the generateThemes task from core/themes; change the theme files, not this.\n" +
        "package org.greylocklabs.ui\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\n" +
        "/** The built-in themes, as every Greylock Labs app ships them. */\nobject Themes {\n$themes" +
        "  /** Every built-in theme, by file name. */\n  val all: List<ThemeTokens> = listOf($all)\n}\n",
    )
  }

  private fun camel(key: String) = key.split("-").mapIndexed { i, part -> if (i == 0) part else part.replaceFirstChar(Char::uppercase) }.joinToString("")

  /** The sections Kotlin needs, each key's value as TOML writes it: quoted strings, bare numbers. */
  private fun read(theme: java.io.File): Map<String, Map<String, String>> {
    val wanted = setOf("theme", "colors", "shape", "type", "motion")
    val sections = mutableMapOf<String, MutableMap<String, String>>()
    var section = ""
    val entry = Regex("""^([a-z-]+)\s*=\s*("[^"]*"|[0-9.]+|true|false)""")
    for (raw in theme.readLines()) {
      val line = raw.substringBefore(" #").trim()
      if (line.startsWith("[")) {
        section = line.trim('[', ']')
      } else if (section in wanted) {
        entry.find(line)?.destructured?.let { (key, value) -> sections.getOrPut(section) { mutableMapOf() }[key] = value }
      }
    }
    return sections
  }
}

val generateThemes = tasks.register<GenerateThemes>("generateThemes") {
  themes.set(layout.projectDirectory.dir("../../themes"))
}

/** Puts core's fonts where Android finds them, under the lowercase names resources need. */
abstract class CopyFonts : DefaultTask() {
  @get:InputDirectory
  abstract val fonts: DirectoryProperty

  @get:OutputDirectory
  abstract val outputDir: DirectoryProperty

  @TaskAction
  fun copy() {
    for (name in listOf("Nunito", "Fraunces")) {
      fonts.get().file("$name-Variable.ttf").asFile.copyTo(outputDir.get().file("font/${name.lowercase()}.ttf").asFile, true)
    }
  }
}

val copyFonts = tasks.register<CopyFonts>("copyFonts") {
  fonts.set(layout.projectDirectory.dir("../../fonts"))
}

androidComponents {
  onVariants { variant ->
    variant.sources.kotlin?.addGeneratedSourceDirectory(generateThemes, GenerateThemes::outputDir)
    variant.sources.res?.addGeneratedSourceDirectory(copyFonts, CopyFonts::outputDir)
  }
}

